async def init_db():
    async with aiosqlite.connect(DB_PATH) as db:
        await db.execute("""
            CREATE TABLE IF NOT EXISTS users (
                user_id INTEGER PRIMARY KEY,
                name TEXT,
                mod1 INTEGER DEFAULT 0,
                mod2 INTEGER DEFAULT 0,
                mod3 INTEGER DEFAULT 0,
                mod4 INTEGER DEFAULT 0,
                certificate_received INTEGER DEFAULT 0
            )
        """)
        await db.commit()


async def save_user(user_id: int, name: str):
    async with aiosqlite.connect(DB_PATH) as db:
        await db.execute(
            "INSERT OR IGNORE INTO users (user_id, name) VALUES (?, ?)",
            (user_id, name)
        )
        await db.execute(
            "UPDATE users SET name = ? WHERE user_id = ?",
            (name, user_id)
        )
        await db.commit()


async def mark_module_done(user_id: int, module: str):
    async with aiosqlite.connect(DB_PATH) as db:
        await db.execute(f"UPDATE users SET {module} = 1 WHERE user_id = ?", (user_id,))
        await db.commit()


async def get_user(user_id: int):
    async with aiosqlite.connect(DB_PATH) as db:
        async with db.execute("SELECT * FROM users WHERE user_id = ?", (user_id,)) as cursor:
            row = await cursor.fetchone()
            if row:
                return {
                    "user_id": row[0],
                    "name": row[1],
                    "mod1": row[2],
                    "mod2": row[3],
                    "mod3": row[4],
                    "mod4": row[5],
                    "certificate_received": row[6]
                }
            return None


async def can_get_certificate(user_id: int) -> bool:
    user = await get_user(user_id)
    if not user:
        return False
    return bool(user["mod1"] and user["mod2"] and user["mod3"] and user["mod4"] and not user["certificate_received"])


async def mark_certificate_received(user_id: int):
    async with aiosqlite.connect(DB_PATH) as db:
        await db.execute("UPDATE users SET certificate_received = 1 WHERE user_id = ?", (user_id,))
        await db.commit()


